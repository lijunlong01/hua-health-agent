def detect_cn(text):
    return any('一' <= ch <= '鿿' for ch in text)


def kb_answer(text):
    best, best_score = None, 0
    for kws, en, zh in KB:
        score = sum(1 for k in kws if k in text.lower())
        if score > best_score:
            best, best_score = (en, zh), score
    if best is None:
        return None
    return best[1] if detect_cn(text) else best[0]
